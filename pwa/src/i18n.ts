// interpolación es simple sustitución de {var}.

export type Idioma = 'es' | 'fr' | 'en';

const CLAVE_LOCALSTORAGE = 'idioma';

export function idiomaActual(): Idioma {
  const guardado = localStorage.getItem(CLAVE_LOCALSTORAGE);
  return guardado === 'fr' || guardado === 'en' ? guardado : 'es';
}

export function fijarIdioma(idioma: Idioma): void {
  localStorage.setItem(CLAVE_LOCALSTORAGE, idioma);
}

// Código BCP-47 para la síntesis de voz del navegador.
export function localeVoz(idioma: Idioma): string {
  return { es: 'es-ES', fr: 'fr-FR', en: 'en-US' }[idioma];
}

// Para Number.prototype.toLocaleString (separador de miles en los importes).
export function localeNumero(idioma: Idioma): string {
  return { es: 'es-ES', fr: 'fr-FR', en: 'en-US' }[idioma];
}

