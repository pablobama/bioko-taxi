// El tipo de la función de traducción, para que los componentes no tengan
// que reconstruirlo con ReturnType cada uno por su lado.
export type T = ReturnType<typeof crearT>;

const DICCIONARIOS: Record<Idioma, Diccionario> = { es, fr, en };

// t('clave', {var: valor}) — si falta la clave en el idioma activo, cae al
// español; si falta también ahí, devuelve la propia clave (visible en
// desarrollo, nunca silenciosamente vacío).
export function crearT(idioma: Idioma) {
  return (clave: string, vars?: Record<string, string | number>): string => {
    let texto = DICCIONARIOS[idioma][clave] ?? es[clave] ?? clave;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        texto = texto.replace(`{${k}}`, String(v));
      }
    }
    return texto;
  };
}
